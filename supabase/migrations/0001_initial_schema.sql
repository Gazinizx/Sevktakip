create extension if not exists pgcrypto;
do $$ begin create type public.app_role as enum ('depo', 'sube', 'yonetici'); exception when duplicate_object then null; end $$;
do $$ begin create type public.order_status as enum ('bekliyor', 'hazirlaniyor', 'sevk_edildi', 'teslim_alindi', 'iptal'); exception when duplicate_object then null; end $$;

create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null default '',
 role public.app_role not null default 'sube',
 branch_name text,
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.branches (
 id uuid primary key default gen_random_uuid(), name text not null unique,
 active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.products (
 id uuid primary key default gen_random_uuid(), name text not null unique,
 category text not null default 'Genel', unit text not null default 'adet',
 minimum_quantity numeric(12,3) not null default 0 check (minimum_quantity >= 0),
 active boolean not null default true, created_at timestamptz not null default now()
);
create table if not exists public.stock_batches (
 id uuid primary key default gen_random_uuid(), product_id uuid not null references public.products(id),
 location_type text not null check (location_type in ('depo','sube')),
 branch_id uuid references public.branches(id), expiry_date date not null,
 quantity numeric(12,3) not null default 0 check (quantity >= 0),
 received_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 check ((location_type = 'depo' and branch_id is null) or (location_type = 'sube' and branch_id is not null))
);
create table if not exists public.orders (
 id uuid primary key default gen_random_uuid(), order_number bigint generated by default as identity unique,
 branch_id uuid not null references public.branches(id), created_by uuid references auth.users(id),
 status public.order_status not null default 'bekliyor', note text not null default '',
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.order_lines (
 id uuid primary key default gen_random_uuid(), order_id uuid not null references public.orders(id) on delete cascade,
 product_id uuid not null references public.products(id), requested_quantity numeric(12,3) not null check (requested_quantity > 0),
 dispatched_quantity numeric(12,3) not null default 0 check (dispatched_quantity >= 0 and dispatched_quantity <= requested_quantity)
);
create table if not exists public.dispatches (
 id uuid primary key default gen_random_uuid(), order_id uuid not null references public.orders(id),
 created_by uuid references auth.users(id), dispatched_at timestamptz not null default now(),
 received_at timestamptz, received_by uuid references auth.users(id), note text not null default ''
);
create table if not exists public.dispatch_lines (
 id uuid primary key default gen_random_uuid(), dispatch_id uuid not null references public.dispatches(id) on delete cascade,
 order_line_id uuid not null references public.order_lines(id), stock_batch_id uuid not null references public.stock_batches(id),
 quantity numeric(12,3) not null check (quantity > 0)
);
create table if not exists public.stock_movements (
 id uuid primary key default gen_random_uuid(), product_id uuid not null references public.products(id),
 stock_batch_id uuid references public.stock_batches(id),
 movement_type text not null check (movement_type in ('giris','sevkiyat','teslim_alma','iade','duzeltme','fire')),
 quantity_delta numeric(12,3) not null check (quantity_delta <> 0), reference_type text, reference_id uuid,
 performed_by uuid references auth.users(id), created_at timestamptz not null default now(), note text not null default ''
);
create table if not exists public.purchase_requests (
 id uuid primary key default gen_random_uuid(), product_id uuid not null references public.products(id),
 requested_quantity numeric(12,3) not null check (requested_quantity > 0),
 status text not null default 'taslak' check (status in ('taslak','gonderildi','karsilandi','iptal')),
 created_by uuid references auth.users(id), created_at timestamptz not null default now(), note text not null default ''
);
create index if not exists stock_batches_product_expiry_idx on public.stock_batches(product_id, expiry_date);
create unique index if not exists stock_batches_branch_expiry_unique on public.stock_batches(product_id, location_type, (coalesce(branch_id, '00000000-0000-0000-0000-000000000000'::uuid)), expiry_date);
create index if not exists orders_status_created_idx on public.orders(status, created_at desc);
create index if not exists stock_movements_created_idx on public.stock_movements(created_at desc);

create or replace function public.current_app_role()
returns public.app_role language sql stable security definer set search_path = public
as $$ select role from public.profiles where id = auth.uid() and active = true $$;

create or replace function public.is_depot_or_manager()
returns boolean language sql stable security definer set search_path = public
as $$ select coalesce(public.current_app_role() in ('depo','yonetici'), false) $$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$ begin
 insert into public.profiles(id, full_name, role)
 values (new.id, coalesce(new.raw_user_meta_data->>'full_name',''), 'sube')
 on conflict (id) do nothing;
 return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

