drop policy if exists "profile read own or manager" on public.profiles;
create policy "profile read own or manager" on public.profiles for select to authenticated
using (id = auth.uid() or public.current_app_role() = 'yonetici');
drop policy if exists "branches read authenticated" on public.branches;
create policy "branches read authenticated" on public.branches for select to authenticated using (active or public.current_app_role() = 'yonetici');
drop policy if exists "branches manage manager" on public.branches;
create policy "branches manage manager" on public.branches for all to authenticated using (public.current_app_role() = 'yonetici') with check (public.current_app_role() = 'yonetici');
drop policy if exists "products read authenticated" on public.products;
create policy "products read authenticated" on public.products for select to authenticated using (active or public.is_depot_or_manager());
drop policy if exists "products manage depot" on public.products;
create policy "products manage depot" on public.products for all to authenticated using (public.is_depot_or_manager()) with check (public.is_depot_or_manager());
drop policy if exists "stock read authenticated" on public.stock_batches;
create policy "stock read authenticated" on public.stock_batches for select to authenticated using (public.is_depot_or_manager() or (location_type = 'sube' and branch_id in (select id from public.branches where name = (select branch_name from public.profiles where id = auth.uid()))));
drop policy if exists "orders read own branch or depot" on public.orders;
create policy "orders read own branch or depot" on public.orders for select to authenticated using (public.is_depot_or_manager() or branch_id in (select id from public.branches where name = (select branch_name from public.profiles where id = auth.uid())));
drop policy if exists "branch create own orders" on public.orders;
create policy "branch create own orders" on public.orders for insert to authenticated with check (public.current_app_role() = 'sube' and created_by = auth.uid() and branch_id in (select id from public.branches where name = (select branch_name from public.profiles where id = auth.uid())));
drop policy if exists "depot update orders" on public.orders;
create policy "depot update orders" on public.orders for update to authenticated using (public.is_depot_or_manager()) with check (public.is_depot_or_manager());
drop policy if exists "order lines read related orders" on public.order_lines;
create policy "order lines read related orders" on public.order_lines for select to authenticated using (exists (select 1 from public.orders o where o.id = order_id and (public.is_depot_or_manager() or o.branch_id in (select id from public.branches where name = (select branch_name from public.profiles where id = auth.uid())))));
drop policy if exists "branch create order lines" on public.order_lines;
create policy "branch create order lines" on public.order_lines for insert to authenticated with check (public.current_app_role() = 'sube' and exists (select 1 from public.orders o where o.id = order_id and o.created_by = auth.uid()));
drop policy if exists "depot update order lines" on public.order_lines;
create policy "depot update order lines" on public.order_lines for update to authenticated using (public.is_depot_or_manager()) with check (public.is_depot_or_manager());
drop policy if exists "dispatch read related" on public.dispatches;
create policy "dispatch read related" on public.dispatches for select to authenticated using (public.is_depot_or_manager() or exists (select 1 from public.orders o where o.id = order_id and o.branch_id in (select id from public.branches where name = (select branch_name from public.profiles where id = auth.uid()))));
drop policy if exists "dispatch lines read related" on public.dispatch_lines;
create policy "dispatch lines read related" on public.dispatch_lines for select to authenticated using (exists (select 1 from public.dispatches d join public.orders o on o.id=d.order_id where d.id=dispatch_id and (public.is_depot_or_manager() or o.branch_id in (select id from public.branches where name = (select branch_name from public.profiles where id = auth.uid())))));
drop policy if exists "stock movements read depot" on public.stock_movements;
create policy "stock movements read depot" on public.stock_movements for select to authenticated using (public.is_depot_or_manager());
drop policy if exists "purchase requests read depot" on public.purchase_requests;
create policy "purchase requests read depot" on public.purchase_requests for select to authenticated using (public.is_depot_or_manager());
drop policy if exists "purchase requests create depot" on public.purchase_requests;
create policy "purchase requests create depot" on public.purchase_requests for insert to authenticated with check (public.is_depot_or_manager() and created_by = auth.uid());

create or replace function public.receive_stock(p_product_id uuid, p_quantity numeric, p_expiry_date date, p_note text default '')
returns uuid language plpgsql security definer set search_path = public
as $$ declare v_batch_id uuid;
begin
 if auth.uid() is null or not public.is_depot_or_manager() then raise exception 'Depo yetkisi gerekli'; end if;
 if p_quantity <= 0 or p_expiry_date is null or p_expiry_date < current_date then raise exception 'Miktar pozitif olmalı ve SKT bugün veya ileri bir tarih olmalı'; end if;
 if not exists(select 1 from public.products where id=p_product_id and active=true) then raise exception 'Ürün bulunamadı veya pasif'; end if;
 insert into public.stock_batches(product_id, location_type, branch_id, expiry_date, quantity)
 values(p_product_id,'depo',null,p_expiry_date,p_quantity)
 on conflict (product_id, location_type, (coalesce(branch_id, '00000000-0000-0000-0000-000000000000'::uuid)), expiry_date)
 do update set quantity=public.stock_batches.quantity + excluded.quantity, updated_at=now()
 returning id into v_batch_id;
 insert into public.stock_movements(product_id,stock_batch_id,movement_type,quantity_delta,reference_type,reference_id,performed_by,note)
 values(p_product_id,v_batch_id,'giris',p_quantity,'stock_batch',v_batch_id,auth.uid(),coalesce(p_note,''));
 return v_batch_id;
end $$;

create or replace function public.create_branch_order(p_branch_id uuid, p_lines jsonb, p_note text default '')
returns uuid language plpgsql security definer set search_path = public
as $$ declare v_order_id uuid; v_line jsonb; v_product_id uuid; v_qty numeric;
begin
 if auth.uid() is null or public.current_app_role() <> 'sube' then raise exception 'Şube hesabı gerekli'; end if;
 if not exists(select 1 from public.profiles p join public.branches b on b.name=p.branch_name where p.id=auth.uid() and b.id=p_branch_id and b.active) then raise exception 'Bu şube için sipariş yetkiniz yok'; end if;
 if jsonb_typeof(p_lines) <> 'array' or jsonb_array_length(p_lines)=0 then raise exception 'Sipariş en az bir ürün içermeli'; end if;
 insert into public.orders(branch_id,created_by,note) values(p_branch_id,auth.uid(),coalesce(p_note,'')) returning id into v_order_id;
 for v_line in select value from jsonb_array_elements(p_lines) loop
   v_product_id := (v_line->>'product_id')::uuid; v_qty := (v_line->>'quantity')::numeric;
   if v_qty <= 0 or not exists(select 1 from public.products where id=v_product_id and active=true) then raise exception 'Sipariş ürün veya miktarı geçersiz'; end if;
   insert into public.order_lines(order_id,product_id,requested_quantity) values(v_order_id,v_product_id,v_qty);
 end loop;
 return v_order_id;
end $$;

create or replace function public.dispatch_order(p_order_id uuid, p_allocations jsonb, p_note text default '')
returns uuid language plpgsql security definer set search_path = public
as $$ declare v_dispatch_id uuid; v_order public.orders%rowtype; v_item jsonb; v_line_id uuid; v_batch_id uuid; v_qty numeric; v_product_id uuid; v_available numeric; v_expected numeric; v_allocated numeric; v_branch_id uuid;
begin
 if auth.uid() is null or not public.is_depot_or_manager() then raise exception 'Depo yetkisi gerekli'; end if;
 select * into v_order from public.orders where id=p_order_id for update;
 if not found or v_order.status not in ('bekliyor','hazirlaniyor') then raise exception 'Sipariş bulunamadı veya sevke uygun değil'; end if;
 if jsonb_typeof(p_allocations) <> 'array' or jsonb_array_length(p_allocations)=0 then raise exception 'SKT bazında sevkiyat dağılımı gerekli'; end if;
 select coalesce(sum(requested_quantity),0) into v_expected from public.order_lines where order_id=p_order_id;
 select coalesce(sum((value->>'quantity')::numeric),0) into v_allocated from jsonb_array_elements(p_allocations);
 if v_allocated <= 0 then raise exception 'Sevk miktarı geçersiz'; end if;
 insert into public.dispatches(order_id,created_by,note) values(p_order_id,auth.uid(),coalesce(p_note,'')) returning id into v_dispatch_id;
 for v_item in select value from jsonb_array_elements(p_allocations) loop
   v_line_id := (v_item->>'order_line_id')::uuid; v_batch_id := (v_item->>'stock_batch_id')::uuid; v_qty := (v_item->>'quantity')::numeric;
   if v_qty <= 0 then raise exception 'Miktar sıfırdan büyük olmalı'; end if;
   select ol.product_id into v_product_id from public.order_lines ol where ol.id=v_line_id and ol.order_id=p_order_id;
   if v_product_id is null then raise exception 'Sipariş satırı geçersiz'; end if;
   select sb.quantity into v_available from public.stock_batches sb where sb.id=v_batch_id and sb.product_id=v_product_id and sb.location_type='depo' and sb.branch_id is null for update;
   if not found or v_available < v_qty then raise exception 'Seçilen SKT stoğu yetersiz'; end if;
   update public.stock_batches set quantity=quantity-v_qty,updated_at=now() where id=v_batch_id;
   insert into public.dispatch_lines(dispatch_id,order_line_id,stock_batch_id,quantity) values(v_dispatch_id,v_line_id,v_batch_id,v_qty);
   insert into public.stock_movements(product_id,stock_batch_id,movement_type,quantity_delta,reference_type,reference_id,performed_by,note)
   values(v_product_id,v_batch_id,'sevkiyat',-v_qty,'dispatch',v_dispatch_id,auth.uid(),coalesce(p_note,''));
 end loop;
 for v_line_id in select id from public.order_lines where order_id=p_order_id loop
   select requested_quantity into v_expected from public.order_lines where id=v_line_id;
   select coalesce(sum(quantity),0) into v_allocated from public.dispatch_lines where dispatch_id=v_dispatch_id and order_line_id=v_line_id;
   if v_allocated <> v_expected then raise exception 'Her sipariş satırı tam karşılanmalı; miktarları kontrol edin'; end if;
   update public.order_lines set dispatched_quantity=v_allocated where id=v_line_id;
 end loop;
 update public.orders set status='sevk_edildi',updated_at=now() where id=p_order_id;
 return v_dispatch_id;
end $$;

create or replace function public.accept_dispatch(p_dispatch_id uuid, p_note text default '')
returns void language plpgsql security definer set search_path = public
as $ declare v_order public.orders%rowtype; v_line record; v_profile_branch text; v_branch_batch_id uuid;
begin
 if auth.uid() is null then raise exception 'Oturum gerekli'; end if;
 select o.* into v_order from public.dispatches d join public.orders o on o.id=d.order_id where d.id=p_dispatch_id for update of d,o;
 if not found or v_order.status <> 'sevk_edildi' then raise exception 'Teslim alınabilecek sevkiyat bulunamadı'; end if;
 select branch_name into v_profile_branch from public.profiles where id=auth.uid() and active=true;
 if public.current_app_role() <> 'yonetici' and (public.current_app_role() <> 'sube' or not exists(select 1 from public.branches where id=v_order.branch_id and name=v_profile_branch)) then raise exception 'Bu şubeye teslim alma yetkiniz yok'; end if;
 for v_line in select dl.quantity, ol.product_id, sb.expiry_date from public.dispatch_lines dl join public.order_lines ol on ol.id=dl.order_line_id join public.stock_batches sb on sb.id=dl.stock_batch_id where dl.dispatch_id=p_dispatch_id loop
   insert into public.stock_batches(product_id,location_type,branch_id,expiry_date,quantity)
   values(v_line.product_id,'sube',v_order.branch_id,v_line.expiry_date,v_line.quantity)
   on conflict (product_id, location_type, (coalesce(branch_id, '00000000-0000-0000-0000-000000000000'::uuid)), expiry_date)
   do update set quantity=public.stock_batches.quantity + excluded.quantity, updated_at=now()
   returning id into v_branch_batch_id;
   insert into public.stock_movements(product_id,stock_batch_id,movement_type,quantity_delta,reference_type,reference_id,performed_by,note)
   values(v_line.product_id,v_branch_batch_id,'teslim_alma',v_line.quantity,'dispatch',p_dispatch_id,auth.uid(),coalesce(p_note,''));
 end loop;
 update public.dispatches set received_at=now(),received_by=auth.uid(),note=case when p_note='' then note else p_note end where id=p_dispatch_id;
 update public.orders set status='teslim_alindi',updated_at=now() where id=v_order.id;
end $$;

